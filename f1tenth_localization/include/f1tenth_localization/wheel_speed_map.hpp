  static constexpr std::size_t kSize = 218;

  static double map(double wheel_speed_mps) noexcept
  {
    if (!std::isfinite(wheel_speed_mps) || wheel_speed_mps <= 0.0) {
      return 0.0;
    }
    if (wheel_speed_mps < kWheelMps.front()) {
      // The identification run did not contain samples below the first
      // breakpoint (0.703 m/s).  Returning zero there made a real low-speed
      // encoder measurement look like a stopped vehicle and forced the
      // observer onto IMU-only propagation.  At low speed the simulator's
      // wheel measurement is already the useful body-speed estimate; use it
      // until the identified map becomes valid.
      return wheel_speed_mps;
    }
    if (wheel_speed_mps >= kWheelMps.back()) {
      return kBodyMps.back();
    }
    const auto upper = std::upper_bound(
      kWheelMps.begin(), kWheelMps.end(), wheel_speed_mps);
    const std::size_t index = static_cast<std::size_t>(
      std::distance(kWheelMps.begin(), upper));
    const double x0 = kWheelMps[index - 1];
    const double x1 = kWheelMps[index];
    const double y0 = kBodyMps[index - 1];
    const double y1 = kBodyMps[index];
    const double ratio = (wheel_speed_mps - x0) / (x1 - x0);
    return y0 + ratio * (y1 - y0);
  }

  static constexpr const std::array<double, kSize> & wheel_breakpoints() noexcept
  {
    return kWheelMps;
  }

  static constexpr const std::array<double, kSize> & body_breakpoints() noexcept
  {
    return kBodyMps;
  }

