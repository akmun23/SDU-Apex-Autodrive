#!/usr/bin/env python3
"""Simulator-free benchmark of the EXACT native-source MPC control-cycle entry.

Uses recorded real Unity source states, live practice raceline and tuning
(cold-start fixtures generated by mpc_source_live_fixture) or real moving-state
QP captures. Calls mpc_rti_solve_cycle through the production native controller
epoch binary, not a simplified QP. The solver's internal monotonic wall clock
includes nominal rollout, source derivatives, QP, nonlinear source acceptance
and state handoff. Does not include ROS/Unity publication overhead.

The no-deadline run estimates required compute time. A second hard-deadline
run establishes whether the correct source-certified plan is publishable.
Optional *synthetic* shared-core CPU contention is NOT a Unity replacement.
"""
from __future__ import annotations
import argparse
import json
import math
import os
import pathlib
import random
import statistics
import subprocess
import sys
from contextlib import ExitStack
from multiprocessing import Event, Process

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEFAULT_BINARY = ROOT / "build/f1tenth_mpc/mpc_native_source_sqp_controller_epoch"
DEFAULT_CASES = {
    "cold_early": pathlib.Path("/tmp/mpc_live_source_fixture_cold_early_20261103"),
    "cold_stable": pathlib.Path("/tmp/mpc_live_source_fixture_cold_stable_20261103"),
}
METRICS = (
    "solver_time_ms",
    "nominal_build_us",
    "derivative_time_ms",
    "qp_time_ms",
    "exact_source_eval_time_ms",
    "source_dual_plant_worker_ms",
    "source_tangent_scoring_worker_ms",
)


def busy_worker(stop: Event, cpu: int) -> None:
    if hasattr(os, "sched_setaffinity"):
        os.sched_setaffinity(0, {cpu})
    os.nice(5)
    v = 0.47
    while not stop.is_set():
        for _ in range(160_000):
            v = (v * 1.0000019 + 0.00000031) % 17.0


def stats(rows: list[float]) -> dict[str, float | None]:
    if not rows:
        return {"median": None, "p95": None, "p99": None, "worst": None}
    values = sorted(rows)
    def percentile(p: float) -> float:
        return values[min(len(values) - 1, math.ceil(len(values) * p) - 1)]
    return {k: round(v, 4) for k,v in (
        ("median", statistics.median(values)), ("p95", percentile(.95)),
        ("p99", percentile(.99)), ("worst", max(values)))}


def benchmark(args: argparse.Namespace) -> dict:
    cores = [int(x) for x in args.cpus.split(",")]
    if len(set(cores)) != len(cores):
        raise ValueError("CPU indices must not repeat")
    for cpu in cores:
        if cpu not in os.sched_getaffinity(0):
            raise ValueError(f"CPU {cpu} is not in current allowed affinity set")
    cases = dict(DEFAULT_CASES)
    for raw in args.cases:
        name,sep,path=raw.partition("=")
        if not sep or not name:
            raise ValueError("--case requires LABEL=/absolute/fixture/directory")
        cases[name] = pathlib.Path(path)
    cases = {k:v for k,v in cases.items() if k in args.selected}
    if not cases:
        raise ValueError("none of the requested case labels exists")
    for name,case in cases.items():
        for filename in ("source_context.mctx", "r1.fqp"):
            if not (case/filename).is_file():
                raise ValueError(f"{name}: missing {filename} at {case}")
    if not args.binary.is_file():
        raise FileNotFoundError(args.binary)

    modes = ("direct", "stage")
    env = os.environ.copy()
    env["OMP_NUM_THREADS"] = str(args.workers)
    env["OMP_PROC_BIND"] = "spread"
    env["OMP_PLACES"] = args.places or "threads"
    env["OPENBLAS_NUM_THREADS"] = "1"
    env["MKL_NUM_THREADS"] = "1"
    args.out.mkdir(parents=True, exist_ok=True)
    # Reuse fixed paths: these files are only written AFTER cycle timing stops.
    controls = args.out/"controls.txt"
    memory = args.out/"memory.bin"
    results = []
    load_stop = Event()
    loads = []
    try:
        if args.load_workers:
            load_cores = ([int(x) for x in args.load_cpus.split(",")]
                          if args.load_cpus else cores)
            for j in range(args.load_workers):
                p=Process(target=busy_worker,args=(load_stop,load_cores[j%len(load_cores)]))
                p.start()
                loads.append(p)
        trials=[(name,mode,i) for name in cases for mode in modes
                for i in range(-args.warmup,args.repeats)]
        random.Random(7216).shuffle(trials)
        for index,(name,mode,trial) in enumerate(trials):
            case=cases[name]
            cmd=["taskset","-c",args.cpus,str(args.binary),str(case),
                 str(controls),str(args.iterations),"-",str(memory),
                 "--full-source-forward","--gn-hessian"]
            if mode=="stage":
                cmd.append("--stage-jacobians")
            if args.deadline_us:
                cmd.append(f"--deadline-us={args.deadline_us}")
            proc=subprocess.run(cmd,env=env,cwd=ROOT,capture_output=True,
                                text=True,timeout=60)
            if proc.returncode:
                raise RuntimeError(
                    f"native tool exited {proc.returncode}, {name}/{mode}: "
                    f"{proc.stderr[-400:]} {proc.stdout[-400:]}")
            item=json.loads(proc.stdout.splitlines()[-1])
            item.update(case=name,mode=mode,trial=trial,
                        load_workers=args.load_workers,
                        cpu_set=args.cpus,
                        deadline_us=args.deadline_us)
            if trial>=0:
                results.append(item)
            if (index+1)%max(1,(len(trials)//8))==0:
                print(f"{index+1}/{len(trials)}",flush=True)
        (args.out/"samples.json").write_text(json.dumps(results,indent=2))
    finally:
        load_stop.set()
        for p in loads:
            p.join(timeout=3)
            if p.is_alive():
                p.terminate()
                p.join(timeout=3)
    groups={}
    for name in cases:
        for mode in modes:
            subset=[s for s in results if s["case"]==name and s["mode"]==mode]
            groups[f"{name}:{mode}"]={
                "trials":len(subset),
                "source_certified_accepts":sum(bool(s["accepted"]) for s in subset),
                "qp_started":sum(s["qp_solves"]>0 for s in subset),
                "at_or_over_20ms":sum(s["solver_time_ms"]>=20 for s in subset),
                "at_or_over_17ms":sum(s["solver_time_ms"]>=17 for s in subset),
                "timing":{k:stats([float(s[k])/(1000. if k=="nominal_build_us" else 1.)
                                    for s in subset]) for k in METRICS},
                "last_status":subset[-1]["status"],
            }
    summary=dict(method="identical_native_mpc_rti_solve_cycle",
                 simulator_running=False,limitations=[
                     "Does not include ROS scheduling, synchronization, publication, Unity physics or model mismatch",
                     "Repeat calls use independent subprocesses and no persisted warm-start memory",
                     "Strict source revalidation by the benchmark runner occurs after its reported cycle timer",
                     "Synthetic CPU load is only a scheduling stressor, not a Unity simulation",
                 ],options=dict(cpus=args.cpus,workers=args.workers,
                       places=args.places or "threads",repeats=args.repeats,
                       iterations=args.iterations,deadline_us=args.deadline_us,
                       synthetic_load_workers=args.load_workers),
                 groups=groups)
    (args.out/"summary.json").write_text(json.dumps(summary,indent=2))
    print(json.dumps(summary,indent=2),flush=True)
    return summary


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--binary",type=pathlib.Path,default=DEFAULT_BINARY)
    p.add_argument("--out",type=pathlib.Path,
                   default=pathlib.Path("/tmp/mpc_source_budget_benchmark"))
    p.add_argument("--cases",action="append",default=[],
                   metavar="LABEL=FIXTURE_DIR")
    p.add_argument("--selected",nargs="+",default=list(DEFAULT_CASES),
                   help="selected case labels, including additional --cases")
    p.add_argument("--cpus",default="2,4,6")
    p.add_argument("--workers",type=int,default=3)
    p.add_argument("--places",default="")
    p.add_argument("--iterations",type=int,default=1)
    p.add_argument("--repeats",type=int,default=20)
    p.add_argument("--warmup",type=int,default=2)
    p.add_argument("--deadline-us",type=int,default=0,
                   help="0=measure needed compute time, positive=hard solver cutoff")
    p.add_argument("--load-workers",type=int,default=0)
    p.add_argument("--load-cpus",default="")
    args=p.parse_args()
    if args.repeats<1 or args.repeats>500 or args.warmup<0 or args.warmup>50:
        p.error("invalid repetitions")
    if args.workers<1 or args.workers>16:
        p.error("invalid OpenMP workers")
    benchmark(args)


if __name__=="__main__":
    main()
